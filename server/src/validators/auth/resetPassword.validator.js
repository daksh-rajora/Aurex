import { body, validationResult } from 'express-validator';

/**
 * Express-validator rules for password reset request.
 */
export const resetPasswordValidatorRules = [
  body('email')
    .trim()
    .notEmpty()
    .withMessage('Email is required')
    .isEmail()
    .withMessage('Please provide a valid email address')
    .normalizeEmail(),
  body('password')
    .notEmpty()
    .withMessage('Password is required')
    .isLength({ min: 8 })
    .withMessage('Password must be at least 8 characters long')
    .isStrongPassword({
      minLength: 8,
      minLowercase: 1,
      minUppercase: 1,
      minNumbers: 1,
      minSymbols: 1,
    })
    .withMessage(
      'Password must contain at least 8 characters, including one uppercase letter, one lowercase letter, one number, and one special character'
    ),
];

/**
 * Validation handler middleware to format and return validation errors.
 */
export const validate = (req, res, next) => {
  const errors = validationResult(req);

  if (!errors.isEmpty()) {
    const formattedErrors = errors.array().map((err) => ({
      field: err.path || err.param,
      message: err.msg,
    }));

    return res.status(400).json({
      success: false,
      message: 'Validation failed',
      errors: formattedErrors,
    });
  }

  next();
};

/**
 * Combined reset password validation middleware chain.
 */
export const resetPasswordValidator = [...resetPasswordValidatorRules, validate];

export default resetPasswordValidator;
